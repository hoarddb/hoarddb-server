package server

import (
	"testing"

	"github.com/hoarddb/hoarddb-bson/bson"
)

// createTypedTestBucket creates a bucket of the given store type.
func createTypedTestBucket(t *testing.T, s *Server, db, bucket string, storeType BucketType) {
	t.Helper()

	if resp, err := s.CreateDatabase(db); err != nil || !resp.Success {
		t.Fatalf("CreateDatabase(%q) = %+v, %v", db, resp, err)
	}
	resp, err := s.CreateBucket(CreateBucketRequest{Database: db, Name: bucket, Type: storeType})
	if err != nil || !resp.Success {
		t.Fatalf("CreateBucket(%q, %s) = %+v, %v", bucket, storeType, resp, err)
	}
}

// TestInsertHonorsDocumentID covers the documented insert contract: a document
// carrying _id_ is stored under that key. Generating a random UUID and dropping
// the developer's key makes every later get/range by that key miss.
func TestInsertHonorsDocumentID(t *testing.T) {
	s := newTestServer(t)
	createTypedTestBucket(t, s, "app", "ledger", BucketTypeBTree)

	resp, err := s.Insert(InsertRequest{
		Database: "app",
		Bucket:   "ledger",
		Data:     map[string]interface{}{"_id_": "k1", "Amount": int64(10)},
	})
	if err != nil || !resp.Success {
		t.Fatalf("Insert = %+v, %v", resp, err)
	}
	if resp.ID != "k1" {
		t.Fatalf("Insert returned id %q, want the document's _id_ %q", resp.ID, "k1")
	}

	found, err := s.Find(FindRequest{Database: "app", Bucket: "ledger", Key: "k1"})
	if err != nil {
		t.Fatalf("Find: %v", err)
	}
	if !found.Found {
		t.Fatalf("Find(k1) = %+v, want the stored document", found)
	}
	var doc map[string]interface{}
	if err := bson.Unmarshal(found.Data, &doc); err != nil {
		t.Fatalf("decode found document: %v", err)
	}
	if doc["Amount"] != int64(10) {
		t.Fatalf("Find(k1) returned %+v, want Amount 10", found.Data)
	}

	// A key generated by the server still works when no _id_ is supplied.
	generated, err := s.Insert(InsertRequest{
		Database: "app",
		Bucket:   "ledger",
		Data:     map[string]interface{}{"Amount": int64(20)},
	})
	if err != nil || !generated.Success {
		t.Fatalf("Insert without _id_ = %+v, %v", generated, err)
	}
	if len(generated.ID) < 8 {
		t.Fatalf("Insert without _id_ returned id %q, want a generated key", generated.ID)
	}
}

// TestBTreeRangeUsesStoredKeys guards the sequence the docs walk through:
// insert two documents by key, then read them back with a bounded range.
func TestBTreeRangeUsesStoredKeys(t *testing.T) {
	s := newTestServer(t)
	createTypedTestBucket(t, s, "app", "ledger", BucketTypeBTree)

	for key, amount := range map[string]int64{"k1": 10, "k2": 20, "k3": 30} {
		if resp, err := s.Insert(InsertRequest{
			Database: "app",
			Bucket:   "ledger",
			Data:     map[string]interface{}{"_id_": key, "Amount": amount},
		}); err != nil || !resp.Success {
			t.Fatalf("Insert(%s) = %+v, %v", key, resp, err)
		}
	}

	got, err := s.RangeQuery(BTreeRangeRequest{Database: "app", Bucket: "ledger", Low: "k1", High: "k2"})
	if err != nil {
		t.Fatalf("RangeQuery: %v", err)
	}
	if len(got.Entries) != 2 {
		t.Fatalf("RangeQuery(k1..k2) returned %d entries (%+v), want 2", len(got.Entries), got.Entries)
	}
	if got.Entries[0].Key != "k1" || got.Entries[1].Key != "k2" {
		t.Fatalf("RangeQuery(k1..k2) keys = %q/%q, want k1/k2", got.Entries[0].Key, got.Entries[1].Key)
	}

	// An unbounded bound must reach past the other keys, not error out.
	unbounded, err := s.RangeQuery(BTreeRangeRequest{Database: "app", Bucket: "ledger", High: "k2"})
	if err != nil {
		t.Fatalf("RangeQuery(..k2): %v", err)
	}
	if len(unbounded.Entries) != 2 {
		t.Fatalf("RangeQuery(..k2) returned %d entries, want 2", len(unbounded.Entries))
	}

	first, err := s.Edge("app", "ledger", false)
	if err != nil {
		t.Fatalf("Edge(first): %v", err)
	}
	if len(first.Entries) != 1 || first.Entries[0].Key != "k1" {
		t.Fatalf("Edge(first) = %+v, want k1", first.Entries)
	}
	last, err := s.Edge("app", "ledger", true)
	if err != nil {
		t.Fatalf("Edge(last): %v", err)
	}
	if len(last.Entries) != 1 || last.Entries[0].Key != "k3" {
		t.Fatalf("Edge(last) = %+v, want k3", last.Entries)
	}
}

// TestBucketStatsReportsLogicalSpace keeps reported bucket size honest: the
// figure is the logical size of what was written, so a store's preallocated
// files (hundreds of megabytes of sparse space) can never be counted as a
// two-document bucket's size. Bytes and Path are empty (spec Q16).
func TestBucketStatsReportsLogicalSpace(t *testing.T) {
	s := newTestServer(t)
	createTypedTestBucket(t, s, "app", "users", BucketTypeHash)

	if resp, err := s.Insert(InsertRequest{
		Database: "app",
		Bucket:   "users",
		Data:     map[string]interface{}{"_id_": "u1", "Email": "dalek@example.com"},
	}); err != nil || !resp.Success {
		t.Fatalf("Insert = %+v, %v", resp, err)
	}

	stats, err := s.BucketStats(BucketStatsRequest{Database: "app", Bucket: "users"})
	if err != nil {
		t.Fatalf("BucketStats: %v", err)
	}
	if !stats.Found {
		t.Fatal("BucketStats reported the bucket as missing")
	}
	if stats.Entries != 1 {
		t.Fatalf("BucketStats entries = %d, want 1", stats.Entries)
	}
	const sane = 32 << 20 // 32 MiB: generous for one document, far below the sparse logs
	if stats.LogicalBytes <= 0 || stats.LogicalBytes > sane {
		t.Fatalf("BucketStats logical bytes = %d, want a positive figure under %d (sparse preallocated files must not be counted)", stats.LogicalBytes, sane)
	}
	if stats.Type != BucketTypeHash {
		t.Fatalf("BucketStats type = %q, want %q", stats.Type, BucketTypeHash)
	}
}
